function n = awgDrainErrors(awg, label)
%AWGDRAINERRORS Empty and print the AWG's SCPI error queue.
%
%   n = awgDrainErrors(awg)
%   n = awgDrainErrors(awg, 'after load')
%
% The error queue is FIFO and only returns ONE entry per query, so a single
% SYSTem:ERRor? tells you almost nothing -- you have to drain it in a loop.
%
% This matters more than it sounds. sendCommand uses fwrite, which reports
% success as soon as the bytes leave the PC. SCPI execution errors are NOT
% raised back to MATLAB; they queue up silently on the instrument. So any
% malformed or unsupported command we have ever sent has failed invisibly.
%
% Call it at the points where you want to know whether the instrument actually
% accepted what we sent:
%
%   awgDrainErrors(awg, 'baseline');     % clear the slate
%   a.run;
%   awgDrainErrors(awg, 'after a run');  % anything here was generated by us
%
% Returns the number of errors drained (0 if the queue was already clean).

    if ~exist('label', 'var'); label = ''; end

    MAX_DRAIN = 200;        % the queue is finite; this is just a runaway guard
    n = 0;

    fprintf('--- AWG error queue %s ---\n', label);
    for k = 1:MAX_DRAIN
        resp = awg.queryRaw('SYSTem:ERRor?', 5);
        if isempty(resp) || strncmp(resp, '0,', 2) || contains(resp, 'No error')
            break
        end
        fprintf('  %3d  %s\n', k, resp);
        n = n + 1;
    end

    if n == 0
        fprintf('  (empty -- the instrument accepted everything)\n');
    else
        fprintf('  %d error(s) drained\n', n);
        if n >= MAX_DRAIN
            fprintf('  WARNING hit the drain guard at %d; there may be more\n', MAX_DRAIN);
        end
    end
end
